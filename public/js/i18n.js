let lang = 'de';
try { const saved = localStorage.getItem('av.lang'); if (saved && DICT[saved]) lang = saved; } catch { /* storage blocked */ }

export function getLang() { return lang; }

export function setLang(next) {
    if (!DICT[next]) return;
    lang = next;
    try { localStorage.setItem('av.lang', next); } catch { /* ignore */ }
    document.documentElement.lang = next;
    apply();
}

export function t(key, vars = {}) {
    const v = (DICT[lang] && DICT[lang][key]) ?? DICT.de[key] ?? key;
    if (typeof v !== 'string') return v;
    return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export function errText(code, detail) {
    const key = 'err_' + code;
    if (DICT[lang][key]) return t(key);
    return t('err_generic', { code: code || detail || '?' });
}

export function apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); el.setAttribute('aria-label', t(el.dataset.i18nTitle)); });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
    document.dispatchEvent(new CustomEvent('av:lang', { detail: lang }));
}

export function fmtNumber(n) {
    return new Intl.NumberFormat(lang === 'de' ? 'de-AT' : 'en-US').format(n);
}

export function fmtDate(unix) {
    if (!unix) return '';
    return new Intl.DateTimeFormat(lang === 'de' ? 'de-AT' : 'en-GB', { day: '2-digit', month: 'short', year: 'numeric' }).format(new Date(unix * 1000));
}

export function fmtBytes(b) {
    if (!b) return '0 B';
    const u = ['B', 'KB', 'MB', 'GB'];
    const i = Math.min(u.length - 1, Math.floor(Math.log(b) / Math.log(1024)));
    const v = b / 1024 ** i;
    return `${v.toFixed(v >= 100 || i === 0 ? 0 : 1).replace('.', lang === 'de' ? ',' : '.')} ${u[i]}`;
}
